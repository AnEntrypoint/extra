const fs = require('fs');
const path = require('path');
const ROOT = '/workspace/extra';
const bad = [];
const py = fs.readFileSync(path.join(ROOT, 'scripts/check-extraction-drift.py'), 'utf8');
const bodies = [...py.matchAll(/'script':\s*'([^']*)'/g)].map(m => m[1]);
const EXPECTED = 'return {objects: api.query({}).length, world: ctx.world.id || null}';
if (bodies.length !== 1) bad.push('expected one exec script in the drift check, found ' + bodies.length);
const body = bodies[0] || '';
if (body !== EXPECTED) bad.push('exec script changed: ' + body.slice(0, 140));
const calls = body.match(/[A-Za-z_][\w.]*\s*\(/g) || [];
const calleeNames = calls.map(c => c.replace(/\s*\($/, ''));
if (JSON.stringify(calleeNames) !== JSON.stringify(['api.query'])) bad.push('calls in exec script are ' + JSON.stringify(calleeNames) + ', expected only api.query');
if (/(^|[^=!<>])=($|[^=])/.test(body)) bad.push('the exec script contains an assignment');
if (/\.(set|update|create|delete|remove|post|put|patch|send|write|insert|spawn|publish|push)\b/i.test(body)) bad.push('the exec script names a mutating member');
const live = py.match(/exec-readonly[^\n]*method='POST'/);
if (!live) bad.push('the exec-readonly request is no longer a POST to agent/exec');
console.log(JSON.stringify({ script: body, calls: calleeNames, liveProbeStillNeedsToken: true, bad }, null, 1));
process.exit(bad.length ? 1 : 0);
